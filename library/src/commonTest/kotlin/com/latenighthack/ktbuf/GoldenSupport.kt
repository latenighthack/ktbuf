package com.latenighthack.ktbuf

import kotlin.test.assertEquals
import kotlin.test.assertTrue

// Shared helpers for the golden tests. Goldens live in WireGoldens.kt as hex strings
// rather than resource files because Kotlin/Native and Kotlin/JS have no common
// resource-loading mechanism -- hex constants are the only form that compiles and
// runs identically on all nine targets.

fun String.hexToBytes(): ByteArray {
    require(length % 2 == 0) { "hex string must have an even length, got $length" }

    return ByteArray(length / 2) { i ->
        val hi = this[i * 2].hexDigit()
        val lo = this[i * 2 + 1].hexDigit()

        ((hi shl 4) or lo).toByte()
    }
}

private fun Char.hexDigit(): Int = when (this) {
    in '0'..'9' -> this - '0'
    in 'a'..'f' -> this - 'a' + 10
    in 'A'..'F' -> this - 'A' + 10
    else -> throw IllegalArgumentException("not a hex digit: '$this'")
}

fun ByteArray.toHex(): String {
    val digits = "0123456789abcdef"
    val builder = StringBuilder(size * 2)

    for (byte in this) {
        val value = byte.toInt() and 0xFF

        builder.append(digits[value shr 4])
        builder.append(digits[value and 0x0F])
    }

    return builder.toString()
}

fun encode(block: ProtobufWriter.() -> Unit): ByteArray = ProtobufOutputStream.encode(block)

fun <T> decode(bytes: ByteArray, block: (ProtobufReader) -> T): T =
    ProtobufInputStream().let { stream ->
        stream.addBytes(bytes)
        stream.read(block)
    }

/** Decodes the first field of [bytes], handing the reader to [block] once positioned. */
fun <T> decodeFirstField(bytes: ByteArray, block: (ProtobufReader) -> T): T =
    decode(bytes) { reader ->
        assertTrue(reader.nextField(), "expected at least one field in ${bytes.toHex()}")
        block(reader)
    }

/** Asserts encoded bytes equal the golden, reporting both as hex so failures are readable. */
fun assertGolden(goldenHex: String, actual: ByteArray, message: String) {
    assertEquals(goldenHex, actual.toHex(), message)
}

/**
 * The core golden assertion: [value] must encode to exactly [goldenHex], and [goldenHex]
 * must decode back to [value]. Checking both directions against externally-generated bytes
 * is what makes these tests immune to mirrored encoder/decoder bugs.
 */
fun <T> assertRoundTrip(
    goldenHex: String,
    value: T,
    label: String,
    write: ProtobufWriter.(T) -> Unit,
    read: (ProtobufReader) -> T
) {
    assertGolden(goldenHex, encode { write(value) }, "$label encoded to the wrong bytes")
    assertEquals(value, decodeFirstField(goldenHex.hexToBytes(), read), "$label decoded to the wrong value")
}
